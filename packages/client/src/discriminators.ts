import { Buffer } from 'buffer';
/**
 * Anchor instruction discriminators for the pinned CrossFlow program.
 *
 * These are `sha256("global:<instruction_name>")[..8]`, written as constants rather than computed
 * at runtime so the client has no dependency on a Node crypto implementation and therefore runs
 * unchanged in a browser. `scripts/check-discriminators.mjs` recomputes every entry from the
 * instruction name and fails on a mismatch.
 */
export const DISCRIMINATORS = {
  initialize_config: [0xd0, 0x7f, 0x15, 0x01, 0xc2, 0xbe, 0xc4, 0x46],
  publish_prices: [0x0c, 0x11, 0x75, 0x9b, 0x8e, 0xf4, 0xd1, 0xac],
  set_pause: [0x3f, 0x20, 0x9a, 0x02, 0x38, 0x67, 0x4f, 0x2d],
  update_policy: [0xd4, 0xf5, 0xf6, 0x07, 0xa3, 0x97, 0x12, 0x39],
  update_admin: [0xa1, 0xb0, 0x28, 0xd5, 0x3c, 0xb8, 0xb3, 0xe4],
  create_and_fund: [0x51, 0xf1, 0x53, 0xb3, 0x13, 0xcb, 0xa7, 0x40],
  settle_thin: [0xd2, 0xe7, 0xa7, 0x45, 0x71, 0x14, 0x76, 0x3c],
  settle_batch: [0x16, 0x02, 0x15, 0xdf, 0xe1, 0x7a, 0xa3, 0xd6],
  settle_routed: [0xf9, 0x3a, 0xb0, 0x2c, 0xd2, 0xdc, 0x77, 0xa7],
  cancel_intent: [0x43, 0x49, 0xee, 0xf4, 0xd0, 0x59, 0xe1, 0x3b],
  withdraw_asset: [0x4e, 0xc1, 0xcf, 0x7d, 0x3f, 0xc1, 0x81, 0x0c],
  recover_closed_vault: [0x67, 0xd2, 0x81, 0x4f, 0xf2, 0xc0, 0x62, 0x2e],
  close_intent: [0x70, 0xf5, 0x9a, 0xf9, 0x39, 0x7e, 0x36, 0x7a],
} as const;

export type InstructionName = keyof typeof DISCRIMINATORS;

export function discriminator(name: InstructionName): Buffer {
  const bytes = DISCRIMINATORS[name];
  if (!bytes) throw new TypeError(`unknown CrossFlow instruction ${name}`);
  return Buffer.from(bytes);
}
